    setNodeVisible(id: number, visible: boolean): void {
        const node = findNode(this.nodes, id);
        if (!node || node.visible === visible) {
            return;
        }
        node.visible = visible;
        this.notify();
    }

    // Sets the opacity (0..1) of the given layers/groups. `history` pushes an
    // undo snapshot first; the Layers panel keeps one entry per slider drag.
    setNodeOpacity(ids: number[], opacity: number, history = true): void {
        const value = Math.max(0, Math.min(1, opacity));
        const targets = ids
            .map((id) => findNode(this.nodes, id))
            .filter((node): node is LayerNode => node !== null);
        if (targets.length === 0 || targets.every((node) => node.opacity === value)) {
            return;
        }
        if (history) {
            this.pushHistory();
        }
        for (const node of targets) {
            node.opacity = value;
        }
        this.notify();
    }

    renameNode(id: number, name: string): void {
        const node = findNode(this.nodes, id);
        const trimmed = name.trim();
        if (!node || trimmed === '' || node.name === trimmed) {
            return;
        }
        this.pushHistory();
        node.name = trimmed;
        this.emit();
    }

    // Moves nodes (with their subtrees) to `parentId` (null = root) at the
    // given index in the bottom-to-top children order. This is the single
    // entry point for drag & drop, including moving nodes into/out of groups.
    moveNodes(ids: number[], parentId: number | null, index: number): void {
        const moving: LayerNode[] = [];
        const wanted = new Set(ids);
        const walk = (nodes: LayerNode[], inside: boolean): void => {
            for (const node of nodes) {
                const match = wanted.has(node.id);
                if (match && !inside) {
                    moving.push(node);
                }
                if (isGroup(node)) {
                    walk(node.children, inside || match);
                }
            }
        };
        walk(this.nodes, false);
        if (moving.length === 0) {
            return;
        }
        const movingIds = new Set(moving.map((node) => node.id));
        // Never move a group into itself or one of its own descendants.
        if (parentId !== null) {
            if (movingIds.has(parentId)) {
                return;
            }
            let ancestor = findParent(this.nodes, parentId);
            while (ancestor) {
                if (movingIds.has(ancestor.id)) {
                    return;
                }
                ancestor = findParent(this.nodes, ancestor.id);
            }
        }
        this.pushHistory();
        this.nodes = removeNodes(this.nodes, movingIds);
        const parent = parentId === null ? null : findNode(this.nodes, parentId);
        if (parentId !== null && (!parent || !isGroup(parent))) {
            // Target vanished (should not happen after validation); restore.
            this.nodes = [...this.nodes, ...moving];
            this.notify();
            return;
        }
        const target = parent ? (parent as LayerGroup).children : this.nodes;
        const at = Math.max(0, Math.min(index, target.length));
        target.splice(at, 0, ...moving);
        this.pruneNodeSelection();
        this.notify();
    }

